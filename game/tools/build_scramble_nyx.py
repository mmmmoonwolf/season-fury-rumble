# ตัวคูณสเกลเฉพาะท่า — ใช้เมื่ออาร์ตต้นฉบับ "ถูกต้องตามภาพ" แต่ไม่ตรงกับที่เกมต้องการ
#
# crouch: วัดแล้วคลิปย่อจริง ไม่ใช่กล้องซูมออก (ขนาดหน้าเท่าเดิม 27.4 -> 27.9 px ระหว่างช่วงยืนกับช่วงย่อ
# ในขณะที่ความสูงตัวลดจาก 488 เหลือ 322 = ย่อลึก 34%) แต่ 34% คือ "นั่งยอง" ซึ่งลึกกว่าที่เกมต้องการ
