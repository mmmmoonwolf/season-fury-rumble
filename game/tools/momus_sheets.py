"""แยกท่าออกจากชีตของ Momus

ใช้ตัวแยกแบบไม่ต้องรู้ตารางของ Orpheus ตรง ๆ — ชีตชุดนี้ก็เจนมาตารางเบี้ยวเหมือนกัน
(ใบ A ได้ 5/4/4 · ใบ C ได้ 4/5 · ใบ D ได้ 5/5 ทั้งที่สั่งไป 3 แถวแถวละ 3)

ที่ต้องเขียนใหม่คือ **ไม้บรรทัดวัดระยะกล้อง** ตัวนี้ใช้ความกว้างหัวไม่ได้:
ผมหยิกฟูของเขาบังกะโหลกทั้งใบ วัดได้ 2.39 หัว ทั้งที่ยืนข้างโรสเตอร์แล้วตัวพอดี
(ปัญหาเดียวกับหมวกของ Alecto ที่วัดได้ 1.81)

ใช้ "รากที่สองของพื้นที่ตัว" แทน แบบเดียวกับ Atlas/Orpheus แต่ไม่ต้องหักอะไรออก
เพราะเขาไม่ได้ถืออาวุธที่หันคนละมุมในแต่ละท่า — พื้นที่ตัวจึงคงที่พอจะเป็นไม้บรรทัดได้
วัดจริง: ชีต B กระจาย ±1.1% · D ±4.8% · C ±7.9% · A ±12.1% (ใบ A มีท่านอนซึ่งเห็นพื้นที่ต่างไป)
"""
import numpy as np

from orpheus_sheets import split

PALE_MIN = 0.04    # สัดส่วนพิกเซลซีด (หน้า+ผ้าพันแผล) ที่ต่ำกว่านี้ = ไม่ใช่ตัวละคร


def figures(path):
    """แยกท่าแล้ว **ทิ้งกล่องที่หลุดออกจากมือ**

    ชีตสกิลของเขามีกล่องไม้ลอยอยู่นอกตัว (ขว้างออกไปแล้ว / ร่วงลงมา)
    ตัวแยกจับก้อนแยกกัน กล่องพวกนั้นจึงถูกนับเป็น "ท่า" ไปด้วย
    วัดจริง: ชีต E แยกได้ 7 ก้อนทั้งที่มี 6 ท่า · ชีต G แยกได้ 10 ก้อนทั้งที่มี 6 ท่า

    ทิ้งได้เลยไม่ต้องเสียดาย เพราะ **กล่องที่ลอยอยู่เป็นกระสุนที่เกมวาดเอง**
    ไม่ใช่ส่วนหนึ่งของเฟรมท่า (กล่องที่ยังอยู่ในมือติดกับตัวอยู่แล้ว ไม่โดนทิ้ง)

    แยกด้วยสัดส่วน "พิกเซลซีด" (หน้าขาวกับผ้าพันแผล) ซึ่งกล่องไม้ไม่มีเลย
    วัดจริง: ท่าจริงต่ำสุด 9.4% · กล่องสูงสุด 0.8% — ห่างกันสิบเท่า ไม่ก้ำกึ่งเลย
    """
    a, masks = split(path)
    r, g, b = (a[:, :, k].astype(int) for k in range(3))
    pale = (r > 185) & (g > 175) & (b > 165) & (np.abs(r - b) < 45)
    keep = [m for m in masks if np.count_nonzero(m & pale) / np.count_nonzero(m) >= PALE_MIN]
    return a, keep


def body_sqrt(m):
    """ไม้บรรทัดวัดระยะกล้อง = รากที่สองของพื้นที่ตัว

    ไม่หักอะไรออกเลย ต่างจาก Orpheus (หักกีตาร์) และ Atlas (หักไฟ)
    เขาไม่มีของติดตัวที่หันคนละมุมในแต่ละท่า กล่อง/หีบอยู่ในชีตสกิลซึ่งหักด้วยสีทีหลัง
    """
    return float(np.sqrt(np.count_nonzero(m)))
