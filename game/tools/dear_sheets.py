import numpy as np

from orpheus_sheets import split

HAIR_MIN = 0.005      # สัดส่วนพิกเซลผมที่ต่ำกว่านี้ = ไม่ใช่ตัวละคร


def hair_mask(a):
    """ผมส้มสดของเขา — ไม่ใช่ผิวหน้า ไม่ใช่โลหะสีทองแดง (ดู docstring ของโมดูล)"""
    r, g, b = (a[:, :, k].astype(int) for k in range(3))
