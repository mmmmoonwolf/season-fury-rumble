/**
 * ขนาดผืนเกม — คิดจากสัดส่วนจอจริง ไม่ fix 16:9 ไว้
 *
 * Phaser Scale.FIT รักษาสัดส่วนผืนเกมไว้เสมอ ผืน 16:9 บนมือถือแนวนอน (ปกติ 19.5:9 ถึง 21:9)
 * จึงเหลือแถบดำซ้ายขวารวมเกือบ 20% ของจอ = อาการ "เล่นแล้วไม่เต็มจอ"
 * ตั้งความกว้างให้ตรงสัดส่วนจอตั้งแต่ตอนสร้างเกม แถบดำจึงหายไปเอง
 *
 * ทำไมปลอดภัย: ความสูงคงที่ 720 เสมอ และกล้องในเกมซูมตาม "ความสูงแมพ" (ดู MainGameScene._setupCamera)
 * จอกว้างขึ้นจึง "เห็นแมพกว้างขึ้น" ไม่ใช่ภาพถูกยืด ส่วน HUD / ล็อบบี้ / ปุ่มสัมผัส อ่านความกว้าง
 * จาก sys.game.config.width อยู่แล้ว จึงขยับตามเอง
 *
 * จอที่เตี้ยกว่า 16:9 (แท็บเล็ต 4:3) ยังเหลือแถบบน-ล่างอยู่ เพราะตรึงความสูงไว้เพื่อไม่ให้
 * สเกลตัวละคร/HUD ที่ปรับมาทั้งเกมเพี้ยน — เป็นการแลกที่ตั้งใจ
 */
export const GAME_HEIGHT = 720;

/** ไม่ให้แคบกว่า 16:9 (เลย์เอาต์ทั้งเกมออกแบบบนสัดส่วนนี้) และไม่ให้กว้างเกินจอ ultrawide */
export const MIN_GAME_WIDTH = 1280;
export const MAX_GAME_WIDTH = 1920;

/**
 * @param winW กว้างหน้าต่างจริง (px)
 * @param winH สูงหน้าต่างจริง (px)
 * @returns ความกว้างผืนเกมที่ควรใช้ คู่กับ GAME_HEIGHT
 */
export function gameWidthFor(winW, winH) {
  // ค่าพัง (0 / NaN / undefined) เกิดได้จริงตอนหน้ายังไม่ layout เสร็จ หรือแท็บถูกซ่อนอยู่
  // ถ้าปล่อยให้ NaN ไหลเข้า Phaser จะได้ canvas ขนาด NaN แล้วจอดำสนิทโดยไม่มี error
  const ratio = winW > 0 && winH > 0 ? winW / winH : MIN_GAME_WIDTH / GAME_HEIGHT;
  return Math.min(MAX_GAME_WIDTH, Math.max(MIN_GAME_WIDTH, Math.round(GAME_HEIGHT * ratio)));
}
